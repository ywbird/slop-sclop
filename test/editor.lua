local I = sclop.input

test('insert and delete keep the cursor', function()
	I:set('', 0)
	I:insert('ab')
	I:insert('한')
	eq(I.text, 'ab한')
	eq(I.pos, 5)
	I:delete(1, 1)
	eq(I.text, 'a한')
	eq(I.pos, 4)
	eq(I:content(1, 3), '한')
end)

test('backspace removes a whole character', function()
	I:set('a한', 4)
	sclop:feedkeys('\127')
	eq(I.text, 'a')
	eq(I.pos, 1)
end)

test('typing goes to the cursor', function()
	I:set('ac', 1)
	sclop:feedkeys('b')
	eq(I.text, 'abc')
	eq(I.pos, 2)
end)

test('word and line kills', function()
	I:set('foo bar  ', 9)
	sclop:feedkeys('\23')
	eq(I.text, 'foo ')
	I:set('one\ntwo three', 13)
	sclop:feedkeys('\21')
	eq(I.text, 'one\n')
	I:set('abc', 1)
	sclop:feedkeys('\11')
	eq(I.text, 'a')
end)

test('line navigation', function()
	I:set('ab\ncd', 4)
	sclop:feedkeys('\1')
	eq(I.pos, 3)
	sclop:feedkeys('\5')
	eq(I.pos, 5)
end)

test('up and down keep the display column', function()
	I:set('한글ab\nxyz', 12)
	sclop:feedkeys('\27[A')
	eq(I.pos, 3) -- column 3 falls inside 글, so the cursor stays after 한
	sclop:feedkeys('\27[B')
	eq(I.pos, 11)
end)

test('newline keys', function()
	I:set('', 0)
	sclop:feedkeys('a\27\rb\10c')
	eq(I.text, 'a\nb\nc')
end)

test('enter submits and history recalls', function()
	local got
	local function h(text)
		got = text
		return true
	end
	sclop.events.subscribe(sclop.events.SUBMIT, h)
	I:set('first', 5)
	sclop:feedkeys('\r')
	I:set('draft', 5)
	sclop:feedkeys('\27[A')
	sclop.events.unsubscribe(sclop.events.SUBMIT, h)
	eq(got, 'first')
	eq(I.text, 'first')
	sclop:feedkeys('\27[B')
	eq(I.text, 'draft')
end)
